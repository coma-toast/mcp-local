import type { ServicePreset, ServiceUpsertRequest } from './types';
import { emptyUpsertRequest } from './components/ServiceEditorForm';

function makeSvc(overrides: Partial<ServiceUpsertRequest>): ServiceUpsertRequest {
  return {
    ...emptyUpsertRequest(),
    ...overrides,
    args: overrides.args ? [...overrides.args] : [],
    env: overrides.env ? { ...overrides.env } : {},
    headers: overrides.headers ? { ...overrides.headers } : {},
    deps: overrides.deps ? [...overrides.deps] : [],
    extra_ports: overrides.extra_ports ? [...overrides.extra_ports] : [],
  };
}

